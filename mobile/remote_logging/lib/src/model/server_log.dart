import 'package:dart_network_layer_core/dart_network_layer_core.dart';
import 'package:remote_logging/remote_logging.dart';
import 'package:remote_logging/src/util/log_record_extension.dart';

/// A model class representing a log entry to be sent to OpenSearch.
class ServerLog extends JsonRequestSchema {
  /// Constructs a [ServerLog] instance.
  ServerLog({
    required this.timestamp,
    required this.loggerName,
    required this.message,
    required this.level,
    required this.zone,
    required this.deviceUUID,
    required this.sessionId,
    this.error,
    this.stacktrace,
  });

  /// Creates a [ServerLog] instance from a [LogRecord].
  factory ServerLog.fromLogRecord(
    LogRecord record,
    IDeviceDataGenerator deviceDataGenerator,
  ) {
    return ServerLog(
      timestamp: record.time,
      loggerName: record.loggerName,
      message: record.message,
      level: record.level.name,
      zone: record.zoneName,
      deviceUUID: deviceDataGenerator.deviceId,
      sessionId: deviceDataGenerator.sessionId,
      error: record.error,
      stacktrace: record.stackTrace,
    );
  }

  /// The timestamp of the log entry.
  final DateTime timestamp;

  /// The logger name or source of the log entry.
  final String loggerName;

  /// The log message.
  final String message;

  /// The log level (e.g., SHOUT, SEVERE, WARNING, INFO).
  final String level;

  /// The zone name where the log was generated.
  final String zone;

  /// The unique identifier for the device. Generated by [IDeviceDataGenerator].
  final String deviceUUID;

  /// The unique identifier for the session. Generated by
  /// [IDeviceDataGenerator].
  final String sessionId;

  /// An optional error object associated with the log entry.
  final Object? error;

  /// An optional stack trace associated
  final StackTrace? stacktrace;

  @override
  Map<String, dynamic> toJsonPayload() => {
    'timestamp': timestamp.toUtc().toIso8601String(),
    'loggerName': loggerName,
    'message': message,
    'level': level,
    'zone': zone,
    'deviceUUID': deviceUUID,
    if (error != null) 'error': error.toString(),
    if (stacktrace != null) 'stacktrace': stacktrace.toString(),
  };
}
