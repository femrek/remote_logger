import 'package:dart_network_layer_core/dart_network_layer_core.dart';
import 'package:remote_logging/remote_logging.dart';
import 'package:remote_logging/src/util/log_record_extension.dart';
import 'package:uuid/uuid.dart';

/// A model class representing a log entry to be sent to OpenSearch.
class ServerLog extends JsonRequestSchema {
  /// Constructs a [ServerLog] instance.
  ServerLog({
    required this.id,
    required this.timestamp,
    required this.loggerName,
    required this.message,
    required this.level,
    required this.zone,
    required this.deviceUUID,
    required this.sessionId,
    this.error,
    this.stacktrace,
  });

  /// Creates a [ServerLog] instance from a [LogRecord], applying field
  /// truncation as specified by [truncation].
  factory ServerLog.fromLogRecord(
    LogRecord record,
    IDeviceDataGenerator deviceDataGenerator,
    LogTruncationConfig truncation,
  ) {
    return ServerLog(
      id: const Uuid().v4(),
      timestamp: record.time,
      loggerName: record.loggerName,
      message: _truncateChars(record.message, truncation.maxMessageChars),
      level: record.level.name,
      zone: record.zoneName,
      deviceUUID: deviceDataGenerator.deviceId,
      sessionId: deviceDataGenerator.sessionId,
      error: record.error == null
          ? null
          : _truncateChars(
              record.error.toString(),
              truncation.maxErrorChars,
            ),
      stacktrace: record.stackTrace == null
          ? null
          : _truncateStacktrace(
              record.stackTrace.toString(),
              truncation.maxStacktraceLines,
              truncation.maxStacktraceLineChars,
            ),
    );
  }

  /// Creates a [ServerLog] instance from a JSON map (used for local storage).
  factory ServerLog.fromJson(Map<String, dynamic> json) {
    return ServerLog(
      id: json['id'] as String,
      timestamp: DateTime.parse(json['timestamp'] as String),
      loggerName: json['loggerName'] as String,
      message: json['message'] as String,
      level: json['level'] as String,
      zone: json['zone'] as String,
      deviceUUID: json['deviceUUID'] as String,
      sessionId: json['sessionId'] as String,
      error: json['error'],
      stacktrace:
          json['stacktrace']
              as String?, // StackTrace is usually stored as String
    );
  }

  /// The unique identifier for this specific log entry.
  ///
  /// Only for saving local database. Is not sent remote.
  final String id;

  /// The timestamp of the log entry.
  final DateTime timestamp;

  /// The logger name or source of the log entry.
  final String loggerName;

  /// The log message.
  final String message;

  /// The log level (e.g., SHOUT, SEVERE, WARNING, INFO).
  final String level;

  /// The zone name where the log was generated.
  final String zone;

  /// The unique identifier for the device. Generated by [IDeviceDataGenerator].
  final String deviceUUID;

  /// The unique identifier for the session. Generated by
  /// [IDeviceDataGenerator].
  final String sessionId;

  /// An optional error object associated with the log entry.
  final Object? error;

  /// An optional stack trace associated with the log entry.
  final String? stacktrace;

  /// The total character count of the variable-length fields.
  ///
  /// Useful for debugging oversized logs and future adaptive batching.
  /// This reflects post-truncation lengths.
  int get charCount =>
      message.length +
      (error?.toString().length ?? 0) +
      (stacktrace?.length ?? 0);

  /// Used to convert this log to a map for local storage.
  Map<String, dynamic> toMap() => {
    'id': id,
    'timestamp': timestamp.toUtc().toIso8601String(),
    'loggerName': loggerName,
    'message': message,
    'level': level,
    'zone': zone,
    'deviceUUID': deviceUUID,
    'sessionId': sessionId,
    if (error != null) 'error': error.toString(),
    if (stacktrace != null) 'stacktrace': stacktrace.toString(),
  };

  @override
  Map<String, dynamic> toJsonPayload() => {
    'timestamp': timestamp.toUtc().toIso8601String(),
    'loggerName': loggerName,
    'message': message,
    'level': level,
    'zone': zone,
    'deviceUUID': deviceUUID,
    if (error != null) 'error': error.toString(),
    if (stacktrace != null) 'stacktrace': stacktrace.toString(),
  };
}

/// Truncates [text] to [maxChars] characters, appending `'...[truncated]'`
/// if the text was shortened. Returns [text] unchanged if [maxChars] is 0.
String _truncateChars(String text, int maxChars) {
  if (maxChars <= 0 || text.length <= maxChars) return text;
  return '${text.substring(0, maxChars)}...[truncated]';
}

/// Truncates a stacktrace string by line count and per-line character limit.
///
/// - [maxLines]: maximum number of lines to retain (0 = unlimited).
/// - [maxLineChars]: maximum characters per line (0 = unlimited).
String _truncateStacktrace(String stacktrace, int maxLines, int maxLineChars) {
  var lines = stacktrace.split('\n');
  var lineTruncated = false;

  if (maxLines > 0 && lines.length > maxLines) {
    lines = lines.sublist(0, maxLines);
    lineTruncated = true;
  }

  if (maxLineChars > 0) {
    lines = lines.map((line) {
      if (line.length > maxLineChars) {
        return '${line.substring(0, maxLineChars)}...[truncated]';
      }
      return line;
    }).toList();
  }

  if (lineTruncated) {
    lines.add('...[truncated]');
  }

  return lines.join('\n');
}
