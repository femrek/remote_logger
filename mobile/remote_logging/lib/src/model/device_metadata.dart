import 'package:dart_network_layer_core/dart_network_layer_core.dart';

/// A data class that holds metadata about the device.
class DeviceMetadata extends JsonRequestSchema {
  /// Constructs a [DeviceMetadata] instance.
  const DeviceMetadata({
    required this.timestamp,
    required this.deviceId,
    required this.sessionId,
    required this.os,
    required this.osVersion,
    required this.model,
    required this.brand,
    required this.device,
    required this.identifier,
    required this.manufacturer,
    required this.isPhysicalDevice,
  });

  /// The timestamp when the metadata was collected. In ISO 8601 format and UTC.
  final String timestamp;

  /// The unique identifier for the device. Generated by `IDeviceDataGenerator`.
  final String deviceId;

  /// The unique identifier for the session. Generated by
  /// `IDeviceDataGenerator`.
  final String sessionId;

  /// The operating system of the device (e.g., Android, iOS).
  final String os;

  /// The version of the operating system.
  final String osVersion;

  /// The model of the device.
  final String model;

  /// The brand of the device.
  final String brand;

  /// The device name.
  final String device;

  /// The device identifier.
  final String identifier;

  /// The manufacturer of the device.
  final String manufacturer;

  /// Indicates whether the device is a physical device or an
  /// emulator/simulator.
  final String isPhysicalDevice;

  @override
  Map<String, dynamic> toJsonPayload() => {
    'timestamp': timestamp,
    'deviceId': deviceId,
    'sessionId': sessionId,
    'os': os,
    'osVersion': osVersion,
    'model': model,
    'brand': brand,
    'device': device,
    'identifier': identifier,
    'manufacturer': manufacturer,
    'isPhysicalDevice': isPhysicalDevice,
  };
}
